function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function replaceTerm(value: string, source: string, target: string) {
  const escaped = escapeRegExp(source);
  const pattern = /^[A-Za-z0-9 -]+$/.test(source) ? `\\b${escaped}\\b` : escaped;
  return value.replace(new RegExp(pattern, "gi"), target);
}

export function fallbackTranslateText(language: ContentLanguage, text: string) {
  if (language === "English") return text;

  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const trimmed = text.trim();
  if (!trimmed) return text;

  const compact = trimmed.replace(/\s+/g, " ");
  const exact = exactTranslations[language][compact] ?? termTranslations[language][compact];
  if (exact) return `${leading}${exact}${trailing}`;

  const replacements = Object.entries(termTranslations[language]).sort((a, b) => b[0].length - a[0].length);
  const translated = replacements.reduce((current, [source, target]) => replaceTerm(current, source, target), compact);
  return `${leading}${translated}${trailing}`;
}

export function fallbackTranslateBatch(language: ContentLanguage, texts: string[]) {
  return Object.fromEntries(texts.map((text) => [text, fallbackTranslateText(language, text)]));
}
